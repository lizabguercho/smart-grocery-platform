"""Parse docs/models/<model>/CHANGELOG.md files and render docs/MODEL_STATUS.md.

The changelogs are the source of truth. The status document is generated from
them and never edited by hand.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

# Order is the normal direction of travel; a model may step back to an earlier
# stage (for example error-analysis after any inference).
STAGES = (
    "baseline-inference",
    "error-analysis",
    "prompt-engineering",
    "inference",
    "fine-tuning",
    "frozen-evaluation",
    "released",
    "monitoring",
)
ENTRY = re.compile(r"^## (\d+\.\d+\.\d+) — (\d{4}-\d{2}-\d{2}) — stage: ([a-z-]+)\s*$")
HEADER_KEYS = ("Owner", "Task", "Depends on", "Next step")


@dataclass(frozen=True)
class ModelStatus:
    model_id: str
    owner: str
    task: str
    depends_on: str
    next_step: str
    version: str
    date: str
    stage: str
    entries: int
    path: str


def parse_changelog(model_id: str, path: Path, root: Path) -> ModelStatus:
    """Read the header block and the newest entry; reject malformed files."""

    text = path.read_text(encoding="utf-8")
    header = {}
    for key in HEADER_KEYS:
        match = re.search(rf"^{key}:[ \t]*(.*)$", text, re.MULTILINE)
        header[key] = match.group(1).strip() if match else ""
    missing = [k for k in ("Owner", "Task", "Next step") if not header[k]]
    if missing:
        raise ValueError(f"{path}: missing header field(s) {missing}")
    entries = [m for line in text.splitlines() if (m := ENTRY.match(line))]
    if not entries:
        raise ValueError(f"{path}: no '## X.Y.Z — YYYY-MM-DD — stage: <stage>' entry")
    versions = [tuple(int(p) for p in m.group(1).split(".")) for m in entries]
    if versions != sorted(versions, reverse=True) or len(set(versions)) != len(
        versions
    ):
        raise ValueError(f"{path}: entries must be newest first with unique versions")
    version, date, stage = entries[0].groups()
    if stage not in STAGES:
        raise ValueError(f"{path}: unknown stage {stage!r}; use one of {STAGES}")
    return ModelStatus(
        model_id,
        header["Owner"],
        header["Task"],
        header["Depends on"],
        header["Next step"],
        version,
        date,
        stage,
        len(entries),
        str(path.relative_to(root)),
    )


def collect(models_dir: Path, root: Path) -> list[ModelStatus]:
    return [
        parse_changelog(p.parent.name, p, root)
        for p in sorted(models_dir.glob("*/CHANGELOG.md"))
    ]


def render_status(statuses: list[ModelStatus]) -> str:
    lines = [
        "# Model status",
        "",
        (
            "<!-- GENERATED by scripts/build_model_status.py from docs/models/*/CHANGELOG.md."
            " Do not edit by hand. -->"
        ),
        "",
        (
            "Where each model stands in the lifecycle described in "
            "[model_lifecycle.md](model_lifecycle.md). The changelog of each model is the source of truth."
        ),
        "",
        "| Model | Version | Stage | Owner | Depends on | Next step | Updated | Changelog |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for s in statuses:
        link = f"[{s.entries} entr{'y' if s.entries == 1 else 'ies'}]({s.path.removeprefix('docs/')})"
        lines.append(
            f"| `{s.model_id}` | {s.version} | **{s.stage}** | {s.owner} | "
            f"{s.depends_on or '–'} | {s.next_step} | {s.date} | {link} |"
        )
    lines += [
        "",
        "Stages, in the normal order: " + " → ".join(f"`{s}`" for s in STAGES) + ".",
        "",
    ]
    return "\n".join(lines)
